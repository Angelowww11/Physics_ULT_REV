const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),{questions}=require('./challenge-source.cjs');
const {readingPrompt,readingTopic}=require('./reading-examples.cjs');
assert.equal(questions.length,600);
for(let m=1;m<=10;m++){
 const qs=questions.filter(q=>q.module===m);assert.equal(qs.length,60);
 assert.equal(qs.filter(q=>q.kind==='numerical').length,45);
 const lines=['### Worked applications: models, calculations, and interpretation','','These worked examples apply the module concepts. Each example states its conditions, explains the model, and shows the complete working.',''];
 for(const [i,q]of qs.entries()){
  assert.equal(new Set(q.choices).size,4);assert.equal(q.reasons.length,4);assert.ok(q.steps.length>=4);
  const topic=readingTopic(q);
  const title=`Worked application ${i+1}: ${topic}`;
  const safe=title.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
  lines.push(`<section class="worked-application">`,'',`<h4 id="${q.solutionAnchor||'worked-'+q.id}">${safe}</h4>`,'',readingPrompt(q),'');
  for(const [j,step]of q.steps.entries()){
   lines.push(`${j+1}. **${step.title}.**${step.text?' '+step.text:''}`,'');
   if(step.tex)lines.push(`   $$${step.tex}$$`,'');
  }
  lines.push(`**Result:** ${q.choices[q.answerIndex]}`,'','</section>','');
 }
 fs.writeFileSync(path.join(root,'notes',`${String(m).padStart(2,'0')}-situations.txt`),lines.join('\n')+'\n');
}
fs.writeFileSync(path.join(root,'challenge-data.js'),'/* Added applications of the supplied module concepts. Generated by tools/build_challenges.cjs. */\nwindow.PhysicsChallenges='+JSON.stringify(questions)+';\n');
console.log('Generated the unchanged 600-question practice bank and 600 complete reading examples.');
